import { expect, test } from "@playwright/test";
import { cameraState, markerPoint, planAtPoint, projectPoints } from "./map-helpers";

test("hidden markers cannot be activated, and View on map reveals them without changing filters", async ({ page }) => {
  await page.goto("/categories/stages/?poi=alchemy-circle#poi-alchemy-circle");
  const host = page.locator("[data-map-enhancement]");
  await expect(host).toHaveAttribute("data-webgl", "ready");
  const markers = page.getByRole("button", { name: "Show markers", exact: true });
  const preview = page.getByRole("region", { name: "Map place preview" });
  await expect(preview).toBeVisible();
  const visibleCanvas = await page.locator("canvas").screenshot();
  await markers.click();
  await expect(markers).toHaveAttribute("aria-pressed", "false");
  await expect(preview).toBeHidden();
  expect((await page.locator("canvas").screenshot()).equals(visibleCanvas)).toBe(false);
  const before = await cameraState(page);
  const point = await markerPoint(page, "alchemy-circle");
  await page.mouse.click(point.x, point.y);
  await expect(page).toHaveURL(/\/categories\/stages\/\?poi=alchemy-circle#poi-alchemy-circle$/);
  await expect(preview).toBeHidden();
  expect(await cameraState(page)).toEqual(before);
  await page.locator("[data-poi-slug='alchemy-circle']").focus();
  await expect(preview).toBeHidden();
  await page.locator("[data-map-locate='alchemy-circle']").click();
  await expect(markers).toHaveAttribute("aria-pressed", "true");
  await expect(preview).toBeFocused();
  await expect(page).toHaveURL(/\/categories\/stages\/\?poi=alchemy-circle#poi-alchemy-circle$/);
});

test("mouse rotation changes both angles, keeps pan anchored, and resets the view", async ({ page }) => {
  await page.goto("/");
  await expect(page.locator("[data-map-enhancement]")).toHaveAttribute("data-webgl", "ready");
  const initial = await cameraState(page);
  const rotate = page.getByRole("button", { name: "Rotate map", exact: true });
  await rotate.click();
  await expect(rotate).toHaveAttribute("aria-pressed", "true");
  const rect = (await page.locator("canvas").boundingBox())!;
  const x = rect.x + rect.width / 2;
  const y = rect.y + rect.height / 2;
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(x + 60, y + 40, { steps: 5 });
  await page.mouse.up();
  await expect.poll(async () => (await cameraState(page)).yawDegrees).toBeCloseTo(24);
  await expect.poll(async () => (await cameraState(page)).pitchDegrees).toBeCloseTo(44);
  expect((await cameraState(page)).distance).toBe(initial.distance);
  await rotate.click();
  const anchor = await planAtPoint(page, x, y);
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(x + 30, y + 15, { steps: 3 });
  await page.mouse.up();
  const projected = (await projectPoints(page, [anchor]))[0]!;
  expect(projected.x).toBeCloseTo(x + 30, 0);
  expect(projected.y).toBeCloseTo(y + 15, 0);
  await rotate.focus();
  await page.keyboard.press("ArrowRight");
  await expect(rotate).toHaveAttribute("aria-pressed", "true");
  await expect.poll(async () => (await cameraState(page)).yawDegrees).toBeCloseTo(39);
  await page.getByRole("button", { name: "Reset view", exact: true }).click();
  await expect.poll(() => cameraState(page)).toEqual(initial);
  await expect(rotate).toHaveAttribute("aria-pressed", "false");
});

test.describe("touch rotation", () => {
  test.use({ hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 } });
  test("one finger rotates, two fingers still zoom, and resize preserves orientation", async ({ page, context }) => {
    await page.goto("/");
    await expect(page.locator("[data-map-enhancement]")).toHaveAttribute("data-webgl", "ready");
    await page.getByRole("button", { name: "Rotate map", exact: true }).tap();
    await page.locator("canvas").scrollIntoViewIfNeeded();
    const rect = (await page.locator("canvas").boundingBox())!;
    const x = rect.x + rect.width / 2;
    const y = rect.y + rect.height / 2;
    const cdp = await context.newCDPSession(page);
    await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ id: 1, x, y }] });
    await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ id: 1, x: x + 40, y: y + 30 }] });
    await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await expect.poll(async () => (await cameraState(page)).yawDegrees).toBeCloseTo(31);
    await expect.poll(async () => (await cameraState(page)).pitchDegrees).toBeCloseTo(40.5);
    const rotated = await cameraState(page);
    const anchor = await planAtPoint(page, x, y);
    await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ id: 1, x: x - 25, y }, { id: 2, x: x + 25, y }] });
    await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ id: 1, x: x - 50, y }, { id: 2, x: x + 50, y }] });
    await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await expect.poll(async () => (await cameraState(page)).distance).toBeCloseTo(rotated.distance / 2);
    const projected = (await projectPoints(page, [anchor]))[0]!;
    expect(Math.hypot(projected.x - x, projected.y - y)).toBeLessThan(4);
    await page.setViewportSize({ width: 844, height: 390 });
    await expect.poll(async () => (await cameraState(page)).yawDegrees).toBeCloseTo(31);
    await expect.poll(async () => (await cameraState(page)).pitchDegrees).toBeCloseTo(40.5);
    expect(Object.values(await cameraState(page)).every(Number.isFinite)).toBe(true);
    await expect(page).toHaveURL(/\/$/);
  });
});
